function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function markerHtml(markers) {
  return markers
    .map(([, left, top], index) => `<span class="marker" style="left:${left}%;top:${top}%">${index + 1}</span>`)
    .join("");
}

function listItems(items) {
  return items.map((item) => `<li>${escapeHtml(item)}</li>`).join("");
}

function stripSectionNumber(title) {
  return String(title).replace(/^\d+\.\s*/, "");
}

function sectionTitle(section, index) {
  return `${index + 1}. ${stripSectionNumber(section.title)}`;
}

